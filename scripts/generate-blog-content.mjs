#!/usr/bin/env node

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contentDirectory = process.env.BLOG_CONTENT_DIRECTORY
  ? resolve(process.env.BLOG_CONTENT_DIRECTORY)
  : resolve(repositoryRoot, "content/blog");
const outputPath = process.env.BLOG_GENERATED_OUTPUT
  ? resolve(process.env.BLOG_GENERATED_OUTPUT)
  : resolve(repositoryRoot, "web/src/blog/generated-content.ts");
const categories = new Set([
  "Método EXECUTA",
  "Produto",
  "IA e agentes",
  "Gestão de projetos",
  "Neurocompatibilidade",
  "Governança",
]);
const coverPatterns = new Set(["grid", "orbit", "steps", "signal", "stack", "bridge"]);

function text(value, label, file) {
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${file}: ${label} is required.`);
  }
  return value.trim();
}

function paragraph(block) {
  return block.join(" ").trim();
}

function parseMarkdown(markdown, file) {
  const h1 = markdown.match(/^#\s+(.+)$/gm) ?? [];
  const h2 = markdown.match(/^##\s+(.+)$/gm) ?? [];
  if (h1.length !== 1) throw new Error(`${file}: exactly one H1 is required.`);
  if (h2.length < 1) throw new Error(`${file}: at least one H2 is required.`);

  const sections = [];
  let current = { heading: "Introdução", paragraphs: [] };
  let paragraphLines = [];

  const flushParagraph = () => {
    const value = paragraph(paragraphLines);
    if (value) current.paragraphs.push(value);
    paragraphLines = [];
  };
  const flushSection = () => {
    flushParagraph();
    if (
      current.paragraphs.length
      || current.bullets?.length
      || current.callout
    ) {
      sections.push(current);
    }
  };

  for (const line of markdown.split(/\r?\n/)) {
    if (/^#\s+/.test(line)) continue;
    const h2Match = line.match(/^##\s+(.+)$/);
    if (h2Match) {
      flushSection();
      current = { heading: h2Match[1].trim(), paragraphs: [] };
      continue;
    }
    if (/^#{3,6}\s+/.test(line)) {
      flushParagraph();
      paragraphLines.push(line.replace(/^#{3,6}\s+/, ""));
      continue;
    }
    const bullet = line.match(/^(?:[-*+]\s+|\d+\.\s+)(.+)$/);
    if (bullet) {
      flushParagraph();
      current.bullets ??= [];
      current.bullets.push(bullet[1].trim());
      continue;
    }
    const callout = line.match(/^>\s*(.+)$/);
    if (callout) {
      flushParagraph();
      current.callout = current.callout
        ? `${current.callout} ${callout[1].trim()}`
        : callout[1].trim();
      continue;
    }
    if (line.trim() === "") {
      flushParagraph();
      continue;
    }
    paragraphLines.push(line.trim());
  }
  flushSection();
  return sections;
}

function buildPost(metadataFile) {
  const metadataPath = resolve(contentDirectory, metadataFile);
  const metadata = JSON.parse(readFileSync(metadataPath, "utf8"));
  const slug = text(metadata.slug, "slug", metadataFile);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
    throw new Error(`${metadataFile}: slug must contain only lowercase letters, numbers and hyphens.`);
  }
  const markdownFile = `${slug}.md`;
  const markdownPath = resolve(contentDirectory, markdownFile);
  if (!existsSync(markdownPath)) throw new Error(`${metadataFile}: ${markdownFile} is missing.`);
  const markdown = readFileSync(markdownPath, "utf8");
  const category = categories.has(metadata.category) ? metadata.category : "Produto";
  const coverPattern = coverPatterns.has(metadata.cover_pattern) ? metadata.cover_pattern : "steps";
  const updatedAt = text(metadata.updated_at, "updated_at", metadataFile);
  return {
    slug,
    title: text(metadata.title, "title", metadataFile),
    excerpt: text(metadata.excerpt, "excerpt", metadataFile),
    category,
    publishedAt: updatedAt.slice(0, 10),
    readingMinutes: Number.isFinite(metadata.reading_minutes)
      ? Math.max(1, Math.round(metadata.reading_minutes))
      : 1,
    featured: false,
    coverPattern,
    coverLabel: typeof metadata.cover_label === "string"
      ? metadata.cover_label
      : `PREVIEW / ${metadata.publication_id ?? slug}`,
    sections: parseMarkdown(markdown, markdownFile),
  };
}

const metadataFiles = existsSync(contentDirectory)
  ? readdirSync(contentDirectory).filter((file) => file.endsWith(".meta.json")).sort()
  : [];
const posts = metadataFiles
  .map(buildPost)
  .sort((left, right) => right.publishedAt.localeCompare(left.publishedAt));
if (new Set(posts.map((post) => post.slug)).size !== posts.length) {
  throw new Error("Generated editorial posts contain duplicate slugs.");
}
const output = `// Generated by scripts/generate-blog-content.mjs. Do not edit manually.
import type { BlogPost } from "./types";

export const generatedBlogPosts: BlogPost[] = ${JSON.stringify(posts, null, 2)};
`;

writeFileSync(outputPath, output, "utf8");
console.log(`Generated ${posts.length} editorial blog post(s).`);
